export const ekitiLgaNames = ekitiLgas.map((lga) => lga.name)

export function getLgaByName(name?: string | null) {
  if (!name) {
    return null
  }

  return ekitiLgas.find((lga) => lga.name === name) ?? null
}

export function getCommunityOptions(lgaName?: string | null) {
  return getLgaByName(lgaName)?.communities ?? []
}

export function getWardOptions(lgaName?: string | null, community?: string | null) {
  const lga = getLgaByName(lgaName)

  if (!lga) {
    return []
  }

  if (!community) {
    return lga.wards
  }

  const normalizedCommunity = community.toLowerCase().replace(/\bekiti\b/g, "").trim()
  const matches = lga.wards.filter((ward) =>
    ward.toLowerCase().includes(normalizedCommunity)
  )

  return matches.length > 0 ? matches : lga.wards
}

